def build() -> list[dict]:
    floating = floating_daily()
    start = date(YEAR, 1, 1)
    end = date(YEAR, 12, 31)
    days: list[dict] = []
    filler_i = 0
    d = start
    while d <= end:
        key = (d.month, d.day)
        entry: dict = {"date": d.isoformat()}

        if key in OFFICIAL:
            title, label = OFFICIAL[key]
            entry["official"] = {"title": title, "short_label": label}
        # Constitution Day also official-like for 11:37
        if key == (12, 12):
            entry["official"] = {
                "title": "День Конституции Российской Федерации",
                "short_label": "С Днём Конституции!",
            }
        # Mother's Day / Trinity as official-tier for morning? Plan says official for 11:37 major —
        # Mother's Day and Trinity go to official if on that date
        if d in floating and floating[d][2] == "folk" and "матери" in floating[d][0].lower():
            entry["official"] = {
                "title": floating[d][0],
                "short_label": floating[d][1],
            }
        if d == date(YEAR, 5, 31) and "Троиц" in floating.get(d, ("", "", ""))[0]:
            entry["official"] = {
                "title": "День Святой Троицы",
                "short_label": "С Троицей!",
            }
        if key == (2, 22):  # Forgiveness Sunday / Maslenitsa peak
            entry.setdefault(
                "official",
                {"title": "Прощёное воскресенье", "short_label": "С Масленицей!"},
            )

        daily = None
        if d in floating:
            t, lab, tier = floating[d]
            daily = {"title": t, "short_label": lab, "tier": tier}
        elif key in FIXED_DAILY:
            t, lab, tier = FIXED_DAILY[key]
            daily = {"title": t, "short_label": lab, "tier": tier}
        else:
            t, lab, tier = FILLERS[filler_i % len(FILLERS)]
            filler_i += 1
            # Slightly unique title with date hint for variety
            daily = {
                "title": t,
                "short_label": lab,
                "tier": tier,
            }

        # Cosmonautics day coincides with Easter 2026 — keep both: official Easter, daily cosm
        if key == (4, 12):
            daily = {
                "title": "День космонавтики",
                "short_label": "С Днём космонавтики!",
                "tier": "memorial",
            }

        entry["daily"] = daily
        days.append(entry)
        d += timedelta(days=1)
    return days


def main() -> None:
    days = build()
    assert len(days) == 365, len(days)
    assert len({x["date"] for x in days}) == 365
    for x in days:
        assert x["daily"]["title"] and x["daily"]["short_label"]

    out = Path(__file__).resolve().parents[1] / "app/application/pipeline/postcards/ru_calendar_2026.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = {"year": YEAR, "timezone": "Europe/Moscow", "days": days}
    out.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    official_count = sum(1 for x in days if x.get("official"))
    print(f"Wrote {out} days={len(days)} official={official_count}")


if __name__ == "__main__":
    main()
