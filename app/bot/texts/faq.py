def faq_text(section: str, max_user_id: int | None = None) -> str | None:
    if section == "rss":
        if not rss_allowed(max_user_id):
            return FAQ_BODY["rss_invite"]
        return FAQ_BODY["rss"]
    if section == "video_audio":
        if not video_allowed(max_user_id) and not audio_allowed(max_user_id):
            return FAQ_BODY["video_audio_invite"]
        return FAQ_BODY["video_audio"]
    return FAQ_BODY.get(section)
