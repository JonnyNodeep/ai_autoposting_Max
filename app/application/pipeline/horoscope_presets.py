"""Default blocks config for Astro Oracle (horoscope) channel pipeline."""
from __future__ import annotations

from copy import deepcopy

from app.application.pipeline.normalize import normalize_blocks_config
from app.bot.states.ai_studio import DEFAULT_BLOCKS

# MSK 08:17 / 14:08 / 20:01 → UTC (+3)
MORNING_UTC = "05:17"
MIDDAY_UTC = "11:08"
EVENING_UTC = "17:01"

_SLOT_LABELS_MSK = {
    MORNING_UTC: "08:17",
    MIDDAY_UTC: "14:08",
    EVENING_UTC: "20:01",
}

_BASE_POST_BRIEF = (
    "Ты — тёплый уютный астро-оракул для канала на русском. "
    "Аудитория примерно 25–35 лет и шире. Тон мягко-серьёзный, спокойный, "
    "конкретный, чуть поэтичный — без мемов, без сарказма, без страшилок и рока.\n\n"
    "Можно мягко писать про отношения, карьеру и деньги в позитивном ключе. "
    "Про здоровье — только общий уход за собой (сон, пауза, вода), без диагнозов "
    "и без «будет болеть».\n\n"
    "Запрещено: «звёзды благоволят», пустые «удачный день для начинаний» без детали, "
    "угрозы, паника, медицинские прогнозы, призывы подписаться, ссылки, хэштеги, "
    "реклама, CTA «подпишись на канал».\n\n"
    "Эмодзи уместны и разнообразны, без гирлянды в каждом слове. "
    "Пиши так, чтобы хотелось сохранить пост и заглянуть завтра."
)


def slot_msk_label(slot_time: str) -> str:
    return _SLOT_LABELS_MSK.get(str(slot_time).strip(), str(slot_time).strip())


def _morning_slot_prompt() -> str:
    return (
        "УТРЕННИЙ СЛОТ — гороскоп дня для всех 12 знаков.\n\n"
        "Структура:\n"
        "1) Короткий заголовок с датой/настроением (эмодзи ок).\n"
        "2) 2–3 предложения: общая энергия дня (одна тема на всех).\n"
        "3) Блок по всем 12 знакам по порядку: "
        "♈ Овен, ♉ Телец, ♊ Близнецы, ♋ Рак, ♌ Лев, ♍ Дева, "
        "♎ Весы, ♏ Скорпион, ♐ Стрелец, ♑ Козерог, ♒ Водолей, ♓ Рыбы.\n"
        "На каждый знак: 1–2 коротких предложения + конкретный мягкий совет "
        "или «что лучше поддержать сегодня». У знаков разные углы "
        "(работа / чувства / решение / контакт / тело-ритм) — не копируй одну "
        "формулировку на всех.\n\n"
        "Если сегодня воскресенье: знак дня (из контекста) разбери чуть подробнее "
        "(3–4 предложения), остальные — одной тёплой строкой каждый.\n\n"
        "Объём: читается за ~30–45 секунд своего знака; весь пост без воды. "
        "Без призыва подписаться."
    )


def _midday_slot_prompt() -> str:
    return (
        "ДНЕВНОЙ СЛОТ — витринная рубрика по дню недели (МСК).\n\n"
        "Выбери рубрику строго по дню недели из контекста:\n"
        "— понедельник: любовная совместимость (пара знаков из фокуса);\n"
        "— вторник: деньги и работа (пара или «ты + босс» из фокуса);\n"
        "— среда: чередуй — на чётных календарных днях «страсть и близость», "
        "на нечётных «тихие конфликты знаков и как смягчить»;\n"
        "— четверг: дружба / «ты + мама» / «ты + друг» (из фокуса);\n"
        "— пятница: знаки на свидании (пара из фокуса);\n"
        "— суббота: как знаки ведут себя в жизни (юмор без издёвки, 4–6 знаков "
        "или все коротко);\n"
        "— воскресенье: мягкий большой разбор — один знак дня или «ты и ты сам», "
        "с опорой на фазу луны.\n\n"
        "Используй «Фокус совместимости сегодня» из контекста как основу, "
        "не уходи в случайную другую пару без причины.\n"
        "Совместимость — не только романтика: босс, мама, друг, коллега, "
        "отношение к себе. Конкретно, тепло, с 1–2 практичными советами.\n"
        "Без страшилок и без «подпишись»."
    )


def _evening_slot_prompt() -> str:
    return (
        "ВЕЧЕРНИЙ СЛОТ — ритуал дня по дню недели (МСК).\n\n"
        "— понедельник / среда / пятница: вечерний прогноз — что сегодня вечером "
        "поддержать и что лучше отложить; мягко, 1 общий блок + по желанию "
        "короткие пометки 3–4 знакам, не обязательно все 12;\n"
        "— вторник / четверг: интерактив «выберите число от 1 до 5» с пятью "
        "тёплыми намёками (разговор / возможность / встреча / подарок-деньги / "
        "новость). В начале поста коротко разгадай «вчерашнее число» как "
        "общий мягкий ключ (без претензии, что знаешь выбор читателя) — "
        "5 коротких расшифровок «если держали 1… / 2…». Числа и формулировки "
        "не копируй дословно из недавних постов;\n"
        "— суббота: «кому сегодня повезёт» и «кому лучше помолчать» — доброжелательно, "
        "без стыда и угроз, 2–3 знака в каждой группе;\n"
        "— воскресенье: фраза недели для каждого знака (одна яркая строка на знак) "
        "или короткий тёплый итог недели + намёк на фазу луны.\n\n"
        "Фазу луны упомяни мягко, не в каждом абзаце. Без страшилок, без подписки."
    )


def build_horoscope_blocks_ui() -> dict:
    blocks = deepcopy(DEFAULT_BLOCKS)

    blocks["post_gen"].update(
        {
            "enabled": True,
            "mode": "ai",
            "user_input": _BASE_POST_BRIEF,
            "add_channel_link": False,
            "bold_headings": True,
            "use_emoji": True,
            "comments_enabled": False,
            "topic_queue": [],
            "topic_history": [],
        }
    )
    blocks["image_prompt"].update(
        {
            "enabled": True,
            "mode": "from_topic",
            "instruction": (
                "Уютная мистическая иллюстрация для астро-канала строго по заголовку/теме поста: "
                "мягкий свет, небо, луна или тонкий зодиакальный вайб, тёплая палитра. "
                "Сцена должна отражать смысл заголовка, а не весь текст поста. "
                "Животных и питомцев добавляй только если это прямо следует из темы; "
                "не ставь кошек и других животных как случайный милый декор к уюту. "
                "Без текста, букв, водяных знаков и логотипов на картинке. "
                "Квадратная композиция, высокая детализация, спокойное настроение."
            ),
            "use_visual_style": False,
        }
    )
    blocks["image_gen"].update(
        {
            "enabled": True,
            "allow_text": False,
            "add_watermark": True,
            "aspect_ratio": "1:1",
        }
    )
    blocks["video_gen"].update({"enabled": False})
    blocks["motion_fx"] = {
        "enabled": False,
        "duration_s": 4,
        "preset_group": "auto",
    }
    blocks["story_gen"].update({"enabled": False})
    blocks["tts_gen"].update({"enabled": False})
    blocks["sunor_gen"].update({"enabled": False})
    blocks["drive_video"] = dict(blocks.get("drive_video") or {"enabled": False})
    blocks["drive_video"]["enabled"] = False
    blocks["news_rss"] = dict(blocks.get("news_rss") or {"enabled": False})
    blocks["news_rss"]["enabled"] = False

    blocks["schedule"].update(
        {
            "enabled": True,
            "frequency": "daily",
            "times": [MORNING_UTC, MIDDAY_UTC, EVENING_UTC],
            "per_slot_prompts": True,
            "meditation_pipeline": False,
            "postcard_pipeline": False,
            "podcast_pipeline": False,
            "horoscope_pipeline": True,
            "slot_prompts": {
                MORNING_UTC: _morning_slot_prompt(),
                MIDDAY_UTC: _midday_slot_prompt(),
                EVENING_UTC: _evening_slot_prompt(),
            },
            "slot_image_addons": {
                MORNING_UTC: "утренний рассвет, мягкий свет, свежее небо",
                MIDDAY_UTC: "дневной мягкий свет, тёплые тона, символы связи",
                EVENING_UTC: "вечер, луна, спокойные звёзды, уютный свет",
            },
            "slot_topic_queues": {},
            "slot_topic_history": {},
            "slot_topic_gen_extra": {},
            "slot_sunor_presets": {},
            "slot_image_refs": {},
        }
    )
    return blocks


def build_horoscope_blocks_v2() -> dict:
    return normalize_blocks_config(build_horoscope_blocks_ui())
